import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { buildDependencyEdgeElements } from '../assets/js/modules/dependency-edges.js';
const load = p => readFileSync(new URL(p,import.meta.url),'utf8');
const detail=load('../assets/js/modules/edge-detail.js');
const preview=load('../tools/shared-renderer-preview.mjs');
const html=load('../tools/shared-renderer-preview.html');
assert.match(detail,/if \(d\.kind === 'dependency'\) \{/);
assert.match(detail,/d\.kind === 'dependency' \? '→' : '↔'/);
assert.match(detail,/non prova un cavo fisico/);
assert.match(preview,/cy\.edges\('\[kind = "dependency"\]'\)\.remove\(\)/);
assert.match(preview,/dependenciesVisible && !inRestrictedScope/);
assert.match(html,/id="dependencies"/);
assert.match(html,/id="scope"/);
const nodes=[{id:'a'},{id:'b'},{id:'c'}];
const relation={upstream:'a',downstream:'b',type:'connectivity',source:'manual-confirmed',confirmed:true};
const all=buildDependencyEdgeElements([relation],nodes);
const restricted=buildDependencyEdgeElements([relation],[{id:'a'},{id:'c'}]);
assert.equal(all.length,1);
assert.equal(restricted.length,0);
assert.equal(all[0].data.perLink,false);
console.log('DependencyVisualPreview: PASS (detail semantics, offline controls, scope rejection, no link metrics)');
